//! 壳里唯一一个允许自己动起来的东西 —— 的位置。
//!
//! <h2>🔴 本议题(KUBI-65)里它是空的,而这个「空」是有意的</h2>
//!
//! 后台定时器是 `KUBI-68` 的交付物,它还卡在 `KUBI-63`(原图存储)上:
//! 定时器只负责「什么时候问」,不负责「该不该转归档」——
//! 判据层与存储层怎么切没定完之前,这里没有可以敲的门。
//!
//! 那为什么现在就把这个文件建出来:
//!
//! **因为「唯一的具名注入点」这条约束靠的是有一个具名的地方。**
//! docs/15 §五 的原话是「只有一个定时器,叫 `shell::scheduler`,
//! 别处不许起线程做周期任务」。没有这个文件,下一个要加周期任务的人会
//! 就近在 `main.rs` 里 spawn 一个 —— 那时约束还在文档里,但已经不在代码里了。
//!
//! <h2>这个文件的三条硬约束,现在就生效</h2>
//!
//! | 约束 | 在代码里的形态 | 谁保证 |
//! |---|---|---|
//! | 🔴 不允许发起任何网络请求 | 本模块**不 import 任何 HTTP 客户端** | `build.sh` 步骤 ① grep |
//! | 只负责「什么时候问」,不负责「该不该删」 | 本模块里**不出现 `if now > expire_at` 这类比较** | 人审 + `KUBI-63` 的判据层 |
//! | `background_timer_supported() == false` 时不假装 | 见下 | `platform` trait |
//!
//! 第一条是红线「原图绝不上云、不同步、不共享」的执行装置:
//! 一个能上网的后台定时器就是这条红线的现成破口。

use crate::platform::Platform;

/// 装配定时器。
///
/// 🔴 现在它什么都不装,而且**没有偷偷装一个**:
/// 这个函数体里没有 `tokio::spawn`、没有 `std::thread::spawn`、没有 `interval`。
/// 壳当前不做任何周期性的事,界面上也因此**没有任何「到期自动处理」的承诺**——
/// 「做不出来的东西,界面上不留承诺」(`web/README.md`)。
///
/// `KUBI-68` 落地时,唯一该改的就是这个函数。
pub fn install(platform: &dyn Platform) {
    // 读一次平台能力,是为了让「常驻还是只扫一次」这个分岔在代码里就看得见,
    // 而不是等 KUBI-68 动手时才去发现它挂在哪儿:
    //   true(macOS)  → 常驻;false(iOS/Android)→ 前台启动时扫一次,且界面不留承诺。
    // 🔴 两条都还没实现,所以这里也【没有】任何 spawn / thread / interval。
    // 一个空转的占位线程比没有线程更难被发现,所以宁可一行都不写。
    let _resident_allowed = platform.background_timer_supported();
}
