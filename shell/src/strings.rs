//! 壳里所有面向用户的字符串,一个文件。
//!
//! 集中在这里的理由不是整洁,是**能力边界文案扫描只有一处要扫**(壳技术方案 §六)。
//! 扫描器扫的是全量界面文案,壳新增的每一句都在这个文件里,别处不许再写。
//!
//! 🔴 撞词表时改的是文案,不是词表。
//!
//! <h2>这个文件现在很短,而且应该一直很短</h2>
//!
//! 壳不新增任何界面 —— 界面全部来自内嵌的 `web/dist`。所以这里只会有
//! **壳自己失败时说的话**:窗口开不出来、端口被占、上游连不上。
//! 一旦这里开始出现「盲区」「覆盖率」这类产品词,说明壳长出了第二套界面。

/// 端口被占用时的说明。
///
/// 🔴 不自动换端口,响亮地失败 —— 端口是 origin 的一部分,
/// 换端口会让浏览器侧存的东西静默全部消失(壳技术方案 §3.7 / `R-73`)。
pub fn port_taken(port: u16) -> String {
    format!(
        "本机 {port} 端口已被占用,壳不会改用别的端口。\n\
         换端口会让这台机器上已经存下的本地数据全部读不出来,所以这里选择直接不启动。\n\
         请先腾出该端口:lsof -nP -iTCP:{port} -sTCP:LISTEN"
    )
}

/// 上游不可达时回给页面的 message。
///
/// 形状必须是 `{code,message,traceId}`,状态码必须是 502 ——
/// 前端 `client.ts` 已经把 502/503/504 翻译成一句人话,
/// 返回别的状态码等于让一条已经写好的错误提示失效(壳技术方案 §3.4 规则 6)。
pub const UPSTREAM_UNCONFIGURED: &str = "这个端没有配置上游后端,/api 不可达。";

/// 上游配置了但连不上。
pub const UPSTREAM_UNREACHABLE: &str = "连不上上游后端。";

/// 反代尚未实现(iOS/Android 脚手架阶段走不到这条分支,macOS 落地时由 KUBI-65 移除)。
pub const UPSTREAM_NOT_IMPLEMENTED: &str = "壳的反代尚未实现。";
