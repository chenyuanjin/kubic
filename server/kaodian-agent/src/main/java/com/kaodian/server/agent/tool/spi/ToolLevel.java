package com.kaodian.server.agent.tool.spi;

/**
 * 原子工具的三层分类(照搬 truman-ai §4.2 的 R/C/E,这是它那套设计里最值钱的一条)。
 *
 * <p>分层的意义不在于命名,在于<b>它让「这一轮有没有副作用」成为一个可以被程序回答的问题</b>。
 */
public enum ToolLevel {

    /** 无副作用的读取。可缓存、可并行、失败了重试一次没有代价。 */
    READ,

    /** 纯计算,不碰 IO。 */
    COMPUTE,

    /**
     * 有副作用:写库、发消息、改状态。
     *
     * <p>🔴 <b>今天一个都没有,而且这是刻意的。</b>能力边界(只答「有没有、几次、多久前」)
     * 说的是 agent 不判断对错;但一个能<b>写</b>的 agent 还会带来另一个问题 ——
     * 模型误判一次,用户的覆盖率数据就被改了,而覆盖率是这个产品唯一的那个数。
     * <p>枚举值先留着,是因为 {@code AgentToolBridge} 里那道「EFFECT 需要显式放行」的门
     * 必须在<b>第一个 E 类工具出现之前</b>就存在 —— 等到有了再补,补的人正是想加它的人。
     */
    EFFECT
}
