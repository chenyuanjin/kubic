package com.kaodian.server.tagging;

/**
 * 调一次外部模型之前先问一句「能不能」——{@code M2-打标管线与模型接入} §2.5。
 *
 * <h2>🔴 这个接口存在的全部理由是:不建出那条边</h2>
 *
 * 两条约束正面撞上过:「召回为空不许问」要求这一问发生在<b>召回之后</b>,而召回在
 * {@code kaodian-domain} 里;{@code 接口契约} §11.1 又写死商业化那一侧不进 {@code domain}。
 * 解法是一个函数式接口而不是一次依赖 —— <b>领域层只知道「要调模型前先问一句能不能」,
 * 它不知道问的是谁、凭什么答、答不了的原因是什么。</b>
 *
 * <p>实现落在 {@code kaodian-app},由调用方构造好之后作为参数传进
 * {@link TaggingService#suggest} —— 领域层<b>不注入、不查找、不知道实现类名</b>。
 *
 * <h2>🔴 这份源码里一个字都不说明「拿不到是为什么」</h2>
 *
 * 类名、方法名、javadoc 里都不出现那个词。一旦出现,下一个人就会在这里加一个
 * 「查还剩多少」的方法,而那个方法是那条边的第一节 —— 它需要一个数,那个数有单位,
 * 单位有语义,语义在另一个模块里。判据是一行 grep,而一句「我们这里不谈它」
 * 会让那行 grep 自己命中自己(与 {@code Tenant} 那段同一条纪律)。
 */
public interface ModelCallGate {

    /**
     * 拿一次外部调用的许可。
     *
     * <p>🔴 <b>必须是一次条件更新,不是「先读后写」</b>:并发下两个请求同时看到「还可以再来一次」
     * 会各调一次({@code M2} §2.4)。领域层这一侧看不到实现,所以这句约束写在契约上 ——
     * 实现方违反它,坏掉的是它自己那一侧的不变量。
     *
     * @return {@code false} = 拿不到。<b>领域层不需要知道原因</b>
     */
    boolean acquire();

    /**
     * 退回一次未兑现的许可。
     *
     * <p>🔴 <b>只在「压根没看成」时调用</b>({@code M2} §2.4 那张表):
     * 模型真的看了而没认出来 —— 无匹配、低于阈值、出口自检降级 —— 三种都<b>不退</b>,
     * 因为那一次外部调用<b>真的发生了</b>。退它等于让「宁可丢弃率高」这条纪律变成免费的。
     */
    void release();
}
