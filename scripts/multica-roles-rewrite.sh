squd() { # $1=小队名 $2=工作流正文
  local nm="$1" flow="$2" sid
  sid=$(mc squad list --output json 2>/dev/null | python3 -c "
import sys,json
d=json.load(sys.stdin)
rows=d if isinstance(d,list) else next((v for v in d.values() if isinstance(v,list)),[])
print(next((r.get('id','') for r in rows if r.get('name')=='''$nm'''),''))" 2>/dev/null)
  if [[ -z "$sid" ]]; then bad "$nm 未找到"; return 0; fi
  if [[ $DRY == 1 ]]; then ok "[预演] $nm 写入工作流"; return 0; fi
  if mc squad update "$sid" --instructions "$flow" >/dev/null 2>&1
  then ok "$nm"; else bad "$nm 更新失败"; fi
}

