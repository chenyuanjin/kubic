package com.kaodian.server.profile;

/**
 * 备考档案的存储契约 —— 目标表 {@code user_exam_profile}(`接口契约` §12.9.1)。
 *
 * <h2>为什么先是接口,而且今天的实现是一个文件</h2>
 *
 * 与 {@code AssertionStore} / {@code TouchStore} 逐字同理:docs/technical/INDEX.md §零 写明
 * 数据层落库最早到阶段 1。这个仓库今天<b>一个 {@code .sql} 都没有</b>,
 * 到那天换成 JDBC 只是多一个实现类,表名与四列已经在这里定死。
 *
 * <h2>🔴 这个接口上<b>只有两个方法,没有第三个</b></h2>
 *
 * 没有 {@code history()},没有 {@code findAllVersions()},也没有 {@code delete()}:
 * <ul>
 *   <li>没有历史 —— 留了就长出「你的备考轨迹」,那是学习分析(§12.9.1)。
 *       历史的入口不是「将来再说」,是<b>结构上不存在</b>:{@link #put} 覆盖同一行,
 *       想留历史就得先改这个签名,而改签名是一次谁都看得见的动作</li>
 *   <li>没有删除 —— 「清空」是 {@link #put} 一行两格皆空,不是删掉这一行。
 *       两条路都能到同一个结果时,少的那条永远不会和多的那条分叉</li>
 * </ul>
 *
 * <h2>🔴 这里没有任何以「天数」为返回值的方法</h2>
 *
 * 存的是绝对日期,读出来的也是绝对日期。{@code U3.8} §2.4 的第一道防线在契约上,
 * 而<b>存储层多一个算天数的便利方法,那道防线就从背面被绕过去了</b>。
 */
public interface ExamProfileStore {

    /**
     * 这个用户的备考档案;<b>从没设过时返回 {@code null}</b>。
     *
     * <p>🔴 不要在这里替调用方兜底成一个「两格皆空的档案」:「没设过」与「设过又清空」
     * 在契约上确实是同一件事(§5.4),但那句话是<b>出口</b>上的规则(两个 key 都不出现),
     * 由接口层兑现。存储层把两者混成一个对象,就再也说不清「这一行到底写没写过」——
     * 而将来那次落库要靠这句话决定是 {@code INSERT} 还是 {@code UPDATE}。
     */
    ExamProfile find(long userId);

    /**
     * 写入。🔴 <b>全量覆盖,按 {@code userId} 覆盖同一行,不追加、不留历史。</b>
     *
     * <p>两格皆空的档案<b>照样落一行</b>,不是「什么都不做」:清空是一次真实的写入,
     * {@code updatedAt} 该跟着动。它与「从没设过」在读出口上不可分辨,
     * 但那是出口的事 —— 见 {@link #find}。
     */
    void put(ExamProfile profile);
}
