/// 端口被占用时的拒绝启动文案(docs/15 §3.7 / `R-73`)。
///
/// 这里不提供「自动换一个端口」这条出路,文案上也不留想象空间。
/// 端口是页面地址的一部分,换一次,浏览器形态存的东西全部消失,而且不报错。
/// 响亮地失败,不无声地毁数据。
pub fn port_taken(port: u16, occupant: &str) -> String {
    format!(
        "端口 {port} 被占用,壳拒绝启动。\n\
         \n\
         端口是页面地址的一部分。换一个端口,本机存过的东西会全部对不上,\n\
         而且不会报错 —— 所以壳宁可不启动,也不自己换。\n\
         \n\
         占用它的是:{occupant}\n\
         请先结束它再重开。"
    )
}

/// 查不出占用进程时的替代说法。宁可说不知道,不要猜一个像那么回事的进程名。
pub const OCCUPANT_UNKNOWN: &str = "查不出来(本机没有可用的端口查询工具)";

/// 上游写成 https 时的拒绝启动文案。
///
/// 阶段 1/2 的上游是本机明文回环。真要接线上域名时,证书走系统信任库这条已经写在
/// docs/15 §3.4 规则 8 里,但壳里现在【没有】任何 TLS 栈 ——
/// 与其让它在运行时静默连不上,不如启动时就说清楚这一段还没做。
pub fn upstream_https_unsupported(upstream: &str) -> String {
    format!(
        "上游写的是 {upstream},壳现在只接明文回环上游。\n\
         \n\
         壳里没有引入任何 TLS 栈:回环段不做本地 TLS(docs/15 §3.6),\n\
         而线上上游这一段留给接线上域名的那一天,由 KUBI-65 补。\n\
         现在把 shell.upstream 改回 http://127.0.0.1:8080 再重开。"
    )
}

