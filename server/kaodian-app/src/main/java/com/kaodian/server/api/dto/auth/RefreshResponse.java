package com.kaodian.server.api.dto.auth;

import java.time.Instant;

/**
 * 续期。
 *
 * <h2>为什么<b>不</b>换发新令牌</h2>
 *
 * 令牌轮换(refresh 时签新的、废旧的)在单设备场景是更强的做法,但这个产品要求
 * <b>多设备并存</b>(docs/10 §7.4 / {@code 1.3.1.1.4})。同一账号在手机和电脑上各有一条会话,
 * 而每条会话是独立的一行 —— 轮换只会换掉<b>调用方自己那一条</b>,别人不受影响。
 * <p>
 * 那为什么还是不换:因为同一台设备上并存的多个标签页会同时刷新,
 * 谁先换完谁把其余标签页手里的那一条作废掉,表现为<b>随机掉线</b>。
 * 而这里的令牌本来就是 30 天滑动的 —— 每次调用都在往后滑,
 * <b>轮换要解决的「长期不变的凭证」这个问题,滑动续期已经解决了大半。</b>
 */
public record RefreshResponse(Instant expiresAt) {
}
