upd "深度测试-推理" "对抗性与统计有效性验证" \
'你做对抗性与推理型测试,补功能测试覆盖不到的那半边。默认立场是怀疑。

重点四项:
· 评测集的统计有效性 —— 样本量撑不撑得起「准确率百分之多少」这个断言?
  抽样是分层的还是随手取的?换一批样本结论还成立吗?
· 阈值取向 —— 跑阈值扫描,验证「宁可丢弃率高、不可准确率低」这个取向
  真的被当前阈值实现了,而不只是写在文档里
· 差集正确性 —— 构造边界数据:整组未触达、同一来源重复、跨设备记录、
  时间倒置。验证覆盖度算得对
· 闭集打标的诱导测试 —— 主动构造提示,诱导模型生成候选集之外的新标签。
  只要造出一个新文本,就是红

反向验证是你的主要武器:不去证明「它是对的」,而是尽力证伪。
不确定时判定为未通过 —— 让一个错的通过,比让一个对的重跑一次代价大得多。'

