upd() { # $1=名称 $2=description $3=职责正文
  local nm="$1" desc="$2" body="$3" aid
  aid=$(mc agent list --output json 2>/dev/null | python3 -c "
import sys,json
d=json.load(sys.stdin)
rows=d if isinstance(d,list) else next((v for v in d.values() if isinstance(v,list)),[])
print(next((r.get('id','') for r in rows if r.get('name')=='''$nm'''),''))" 2>/dev/null)
  if [[ -z "$aid" ]]; then bad "$nm 未找到"; return 0; fi
  if [[ $DRY == 1 ]]; then ok "[预演] 重写 $nm"; return 0; fi
  if mc agent update "$aid" --description "$desc" --instructions "${body}${BOUND}" >/dev/null 2>&1
  then ok "$nm"; else bad "$nm 更新失败"; fi
}

# ══════════════ ① 恢复产品开发 ══════════════
say "恢复「产品开发」"
if [[ $DRY == 1 ]]; then
  ok "[预演] restore ${OLD_PROD_ID:0:8} → 改名为「产品开发」"
else
  mc agent restore "$OLD_PROD_ID" >/dev/null 2>&1 && ok "已恢复" || bad "恢复失败(可能未归档)"
  mc agent update "$OLD_PROD_ID" --name "产品开发" >/dev/null 2>&1 && ok "改名为「产品开发」" || bad "改名失败"
fi

say "重写 agent 描述(去文档耦合)"

