//! 🔴 **壳里唯一一个会自己动起来的东西,也是唯一的具名定时器注入点。**
//!
//! 边界比别处划得更死(壳技术方案 §五):
//!
//! | 规则 | 状态 |
//! |---|---|
//! | 只有一个定时器,叫 `shell::scheduler`,别处不许起线程做周期任务 | 本文件是唯一一处 |
//! | 🔴 **不允许发起任何网络请求** | 本模块**不 import 任何 HTTP 客户端**,这就是它在代码里的形态 |
//! | 只负责「什么时候问」,不负责「该不该删」 | 见下面 `tick` 的注释 |
//! | `background_timer_supported() == false` 时**不假装** | 见 `start` |
//!
//! 🔴 一个能上网的后台定时器,就是「原图绝不上云、不同步、不共享」这条红线的现成破口。
//! **给这个文件加一条 HTTP 依赖之前,先去看红线。**

use crate::platform::Platform;

/// 装上定时器。
///
/// <h2>`KUBI-66` 在这里做了什么:什么都没做,而这是对的</h2>
///
/// iOS 的 `background_timer_supported()` 是 `false`,系统不保证后台执行。
/// 方案 §五 写明此时的正确行为是「**前台启动时扫一次**,并且不在界面上承诺任何
/// 『到期自动处理』」。而「扫一次」要扫什么、到期判据是什么、到期之后做什么,
/// 全部是 `KUBI-63`(存储与判据层)和 `KUBI-68`(后台定时器)的活 —— 都还没落地。
///
/// 所以这里**只留注入点,不留行为**。写一个空转的定时器会更像"做完了",
/// 但它什么也不处理,那是在界面之外留了一句假承诺。
pub fn start(platform: &impl Platform) {
    if platform.background_timer_supported() {
        // macOS:进程可常驻,`KUBI-68` 在这里装真正的周期触发。
        // 🔴 装的时候记住:定时器属于**触发**,判据仍在判据层。
        // 这里出现一行 `if now > expire_at` 就已经把两层合并了 ——
        // 而那两层分离是 `KUBI-63` 刻意做的。
        eprintln!("[shell] 本平台支持后台定时器;周期触发由 KUBI-68 落地,当前未装。");
    } else {
        // iOS / Android:系统随时挂起进程,没有任何 API 能承诺「到期那一刻一定跑到」。
        // 🔴 不降级成「假装能跑」—— 做不出来的东西,界面上不留承诺。
        eprintln!("[shell] 本平台不保证后台定时执行;不承诺到期自动处理,只在前台启动时扫一次。");
        tick(platform);
    }
}

/// 前台扫一次。
///
/// 🔴 **只负责「什么时候问」,不负责「该不该删」。**
/// 到期动作的判据与文案由 `KUBI-63` / `KUBI-64` 定,本文件只定注入点。
///
/// 另外记住语义:到期是**转归档**,不是删除 —— 归档后字节仍在本机、仍然读得出来;
/// 用户手按的删除才是真删。两件事不要混(`KUBI-68`)。
fn tick(platform: &impl Platform) {
    // 归档目录现在只是取出来看一眼,没有任何读写 ——
    // 存储层是 `KUBI-63` 的活,`KUBI-66` 不碰。
    let _archive_dir = platform.archive_dir();
}
